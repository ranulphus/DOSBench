#!/usr/bin/env python3
"""Generate the menu's test catalogue from the core's test tables.

  testlist.py OUT.h SOURCES...

Reads the SYN(...), MODEL(...) and LEVEL(...) entries (id, group or file,
description, flags) and writes a C table for src/menu/menu.c, so the menu
lists exactly what the benchmark programs run.
"""
import re
import sys

ENTRY = {
    "SYN": re.compile(r'SYN\("(\w+)",\s*"(\w+)",\s*"([^"]*)",\s*([\w|]+)'),
    "MODEL": re.compile(r'MODEL\("(\w+)",\s*"[\w.]+",\s*"([^"]*)"\)'),
    "LEVEL": re.compile(r'LEVEL\("(\w+)",\s*"[\w.]+",\s*\d+,\s*"([^"]*)"\)'),
}


def main():
    out, srcs = sys.argv[1], sys.argv[2:]
    rows = []
    for path in srcs:
        text = open(path).read()
        for m in ENTRY["SYN"].finditer(text):
            rows.append((m.group(1), m.group(2), m.group(3), "T_GL_ONLY" in m.group(4)))
        for m in ENTRY["MODEL"].finditer(text):
            rows.append((m.group(1), "model", m.group(2), False))
        for m in ENTRY["LEVEL"].finditer(text):
            rows.append((m.group(1), "level", m.group(2), False))
    order = {"basic": 0, "synth": 1, "model": 2, "level": 3}
    rows.sort(key=lambda r: order.get(r[1], 9))
    with open(out, "w") as f:
        f.write("/* GENERATED by tools/testlist.py - do not edit. */\n")
        f.write("static const menu_test menu_tests[] = {\n")
        for tid, grp, what, glonly in rows:
            f.write('    { "%s", "%s", "%s", %d },\n' % (tid, grp, what.replace('"', "'"), int(glonly)))
        f.write("    { 0, 0, 0, 0 }\n};\n")


if __name__ == "__main__":
    main()
